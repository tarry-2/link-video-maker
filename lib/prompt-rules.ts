// 결말 — 답 먼저, 루프는 그 다음, 장르 톤 유지.
//   narrative=true면 서사형(드라마·공포·미스터리)이라 장르 톤 유지 규칙을 더한다.
export function endingRule(opts: {narrative?: boolean} = {}): string {
  const base = `★★★마무리가 영상 성패를 가른다. ${RULE.answer}
답·결과를 분명히 준 뒤, 그 여운이 '맨 처음 장면'과 자연스럽게 이어지도록 닫아 자동 반복을 유도하라(답이 먼저, 루프는 그 다음). 앞에 안 나온 뜬금없는 새 소재로 끝내지 말고, '끝·구독·좋아요' 같은 영상 밖 멘트로 끊지 마라.`;
  const tone = opts.narrative
    ? `\n★이 이야기 장르의 톤 그대로 닫아라 — 공포·스릴러·미스터리면 끝까지 서늘·긴장(여운=소름·충격), 감동이면 뭉클, 복수극이면 통쾌·비장. 억지로 "희망적·따뜻한·평화로운" 엔딩으로 분위기 뒤집지 마라(공포로 달려놓고 밝게 웃으며 끝=최악).`
    : '';
  return base + tone;
}

// 시리즈 — 편마다 다른 주제 + 떡밥→회수→새 떡밥(이번 편 결과는 주되 더 큰 궁금증 남김).
export function seriesRule(episode?: number, total?: number, logline?: string): string {
  if (!episode || !total || total < 2) return '';
  const mid = episode < total;
  return `\n★지금은 전체 ${total}편 중 ${episode}편이다. ${episode > 1 ? '앞 편의 궁금증을 이어받아 풀어주며 시작하라(앞을 본 사람이 "그래서 그렇구나" 싶게).' : '1편이므로 세계관·인물을 자연스럽게 소개하되 초반 3초에 강한 훅.'} ${mid ? '이 편의 핵심 사건·질문은 매듭지어 시청자가 답답하지 않게 하되, 끝에 다음 편으로 이어질 더 큰 궁금증(클리프행어)을 남겨라(이번 편 결과는 주고 새 떡밥을 추가 — 결과 생략 금지).' : '마지막 편이므로 전체 시리즈를 감정적으로 매듭지어 큰 여운.'} ★편마다 주제가 뚜렷이 달라야 한다(같은 내용·같은 후킹 반복 금지).${logline ? `\n이 편에서 벌어질 일: ${logline}` : ''}`;
}

// 길이별 이야기 복잡도 — 길이는 랭킹요소 아님, 완주율이 전부(2026 쇼츠 리서치+테리 실측).
//   짧은데 복잡하면 전개가 급해 망한다.
export function storyStructure(durationSec: number): string {
  if (durationSec <= 35) return `[이야기 구조 — ${durationSec}초 초단편. ★짧으니 '매끄럽게'가 핵심(완주율 65%+)]
- 기교·다단계 금지. 딱 '세팅(2초) → 긴장/핵심 하나 → 한 방(payoff·정보)'으로 군더더기 없이 쭉 이어라.
- ★복잡한 다단계 전개(납치·10년·복수)를 30초에 욱여넣지 마라(전개가 급해 망함). 단순하지만 강한 하나를 끝까지.
- 첫 1~2초에 가장 센 것, 뜸 들이는 도입 금지. 매끄러운 한 호흡으로 끝까지.`;
  if (durationSec <= 60) return `[이야기 구조 — ${durationSec}초 표준 쇼츠. ★완주율 50%+가 생명]
- 기-승-전-결 기본형 + (이야기면)반전 1개·가벼운 복선 하나(갑툭 금지). 매 장면 새 진전, 군더더기 0.
- 마지막은 1번에서 던진 것에 답/정보로 닫는다.`;
  return `[이야기 구조 — ${durationSec}초 롱폼/숏드라마. ★길수록 '후킹→질문→답' 테크닉이 생명(이탈 방지)]
- 긴 영상은 그냥 늘어놓으면 이탈한다. 구간마다 '작은 후킹(질문)을 던지고 → 풀어주고 → 다음 질문'을 반복해 끝까지 끌어라.
- 복잡한 다단계 전개 가능(복선 여러 개, 반전 1~2개). 단 모든 장면은 하나의 로그라인에서 벗어나지 마라.
- 감정을 계단처럼 쌓아 후반 정점, 복선 회수로 "그래서 그랬구나". 매 장면 끝을 다음이 궁금하게 끊어 완주율을 끌어라.`;
}
